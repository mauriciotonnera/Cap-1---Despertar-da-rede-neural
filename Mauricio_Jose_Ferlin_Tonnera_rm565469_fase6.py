DRIVE_BASE = Path('/content//content/drive/content/drive/MyDrive')
DATA_ROOT = DRIVE_BASE / 'datasets' / 'caltech101_ab'
TRAIN_DIR = DATA_ROOT / 'train'
VAL_DIR   = DATA_ROOT / 'val'
TEST_DIR  = DATA_ROOT / 'test'
